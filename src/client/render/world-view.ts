  const yaw = { value: 0 }
  let map: GameMap | null = null
  let sampler: TerrainSampler | null = null
  let climate: ClimateGrid | null = null
  let streamer: Streamer<ChunkData> | null = null
  let heights: HeightField | null = null
  let maxTop = 0
  const IS = S.infinite
  let retainT = 0
  const gen = { prefetched: 0, ensured: 0, lastMs: 0, maxMs: 0, retainMs: 0 }
  let compileTimeouts = 0
  let lightsDirty = false
  let loadMs = 0
  const mapSize = new THREE.Vector2(1, 1)
  const fields = new Map<string, ParticleField>()
  let fieldScale = quality().particleScale
  let builtGrassPerTile = Math.round(quality().grassPerTile)
  let builtDecor = quality().decorDensity
  let builtFringe = quality().terrainFringe
  let poolSize = -1
  let time = 0
  let atlasT = 0
  let minutes = CONTENT.config.time.startMinutes
