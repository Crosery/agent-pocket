// the focus inside a per-frame budget and evicted when far (content/render.json "streaming"), so 1024² maps load fast
// and memory stays bounded. Infinite maps (GameMap.infinite) stream an unbounded chunk grid: a first build stage
// ensures the world chunks it reads (budgeted generation), idle frames prefetch world chunks ahead of the player,
