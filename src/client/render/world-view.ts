  const settings = () => ext?.settings ?? CONTENT.config.defaultSettings
  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)')
  const quality = (): QualityPreset => ext?.quality ?? qualityPreset(settings().quality)
